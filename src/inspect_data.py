import pandas as pd
import numpy as np

print("=== 1. INSPECTING STORES.CSV ===")
stores = pd.read_csv('data/stores.csv')
print(f"Shape: {stores.shape}")
print("Data Types:")
print(stores.dtypes)
print("Missing values:")
print(stores.isnull().sum())
print(f"Unique Stores: {stores['Store'].nunique()}")
print(f"Store Types: {stores['Type'].value_counts().to_dict()}")
print(f"Store Size summary:\n{stores['Size'].describe()}")

print("\n=== 2. INSPECTING FEATURES.CSV ===")
features = pd.read_csv('data/features.csv')
print(f"Shape: {features.shape}")
print("Data Types:")
print(features.dtypes)
print(f"Date range: {features['Date'].min()} to {features['Date'].max()}")
print(f"Unique Stores: {features['Store'].nunique()}")
print("Missing values:")
print(features.isnull().sum())

print("\n=== 3. INSPECTING TRAIN.CSV ===")
train = pd.read_csv('data/train.csv')
print(f"Shape: {train.shape}")
print("Data Types:")
print(train.dtypes)
print(f"Date range: {train['Date'].min()} to {train['Date'].max()}")
print(f"Unique Stores: {train['Store'].nunique()}")
print(f"Unique Departments: {train['Dept'].nunique()}")
print("Missing values:")
print(train.isnull().sum())
print(f"Negative Weekly_Sales: {(train['Weekly_Sales'] < 0).sum()} rows")
print(f"Zero Weekly_Sales: {(train['Weekly_Sales'] == 0).sum()} rows")
print(f"Total sales summary:\n{train['Weekly_Sales'].describe()}")

print("\n=== 4. VERIFYING MERGE ===")
# Department-level merge check
merged_dept = train.merge(features, on=['Store', 'Date', 'IsHoliday'], how='left')
merged_dept = merged_dept.merge(stores, on='Store', how='left')
print(f"Dept-level merged shape: {merged_dept.shape}")
assert len(merged_dept) == len(train), "Row count mismatch in dept-level merge!"

# Aggregated store-level merge check (Scope: Forecast total weekly sales per store)
store_weekly = train.groupby(['Store', 'Date', 'IsHoliday'], as_index=False)['Weekly_Sales'].sum()
print(f"Aggregated store-weekly shape: {store_weekly.shape}")
merged_store = store_weekly.merge(features, on=['Store', 'Date', 'IsHoliday'], how='left')
merged_store = merged_store.merge(stores, on='Store', how='left')
print(f"Store-level merged shape: {merged_store.shape}")
print(f"Merged date range: {merged_store['Date'].min()} to {merged_store['Date'].max()}")
print("Null count in store-level merged:")
print(merged_store.isnull().sum())
print("\nMerge verified successfully with 0 missing values in core features (only MarkDowns have expected NaNs).")
